"""Regenerate docs/CAPABILITY_MAP.md from the live registry (statuses are probed, not hand-written)."""
from pathlib import Path

from video_editor import registry

MANUAL = {
    "Project / review feature (checklist or revision history; judgment stays human)": [
        "Pre-edit story work", "Story-finding and structure", "Emotional judgment", "Script literacy",
        "Time management", "Problem solving", "Adaptability and learning", "Originality judgment",
        "Creator-marketer mindset"],
    "Advanced capability requiring another tool (the app's alternative to these is the Auto/Custom/Chat planner)": [
        "Built-in NLE AI", "Premiere / Resolve / Final Cut / Avid / After Effects / CapCut / Descript / supporting tools"],
    "Market data, not a skill (nothing to implement)": [
        "Upwork / Fiverr / Adobe / BLS demand figures"],
}
STATUS = {"available": "✅ available", "missing_dependency": "⛔ missing dependency",
          "not_implemented": "🚧 not implemented", "external_tool": "🔗 needs another tool",
          "broken_handler": "⚠️ broken"}


def main():
    out = ["# Capability map", "",
           "Generated by `scripts/gen_capability_map.py` from `video_editor/registry.py`. Status is probed at "
           "generation time: a capability is ✅ only if its handler resolves and every dependency passes.", ""]
    kinds = [("feature", "User-facing editing features"), ("planning_rule", "Automatic planning rules"),
             ("project", "Project / review features"), ("external", "Advanced capabilities needing another tool")]
    counts = {}
    for c in registry.CAPS:
        counts[c.status()[0]] = counts.get(c.status()[0], 0) + 1
    out.append("**Totals:** " + ", ".join(f"{STATUS[k]} {v}" for k, v in counts.items()) + "\n")
    for kind, title in kinds:
        caps = [c for c in registry.CAPS if c.kind == kind]
        if not caps:
            continue
        out += [f"## {title}", "", "| id | name | status | handler | dependencies / note | covers (from the skills list) |",
                "|---|---|---|---|---|---|"]
        for c in caps:
            st, why = c.status()
            note = why or ", ".join(c.dependencies) or "—"
            if c.external_tool and st == registry.EXTERNAL:
                note = c.external_tool
            out.append(f"| `{c.id}` | {c.name} | {STATUS[st]} | `{c.handler_ref or '—'}` | {note} | "
                       f"{'; '.join(c.doc_skills) or '—'} |")
        out.append("")
    out += ["## Skills-list entries that are not editing capabilities", ""]
    for k, v in MANUAL.items():
        out.append(f"**{k}**")
        out += [f"- {x}" for x in v]
        out.append("")
    Path(__file__).resolve().parent.parent.joinpath("docs", "CAPABILITY_MAP.md").write_text("\n".join(out))
    print("written", counts)


if __name__ == "__main__":
    main()
